/*
 * Локальный генератор истории — гарантированный запасной вариант.
 *
 * Не зависит ни от каких внешних сервисов, поэтому клиент получает
 * персональную историю, даже если все ИИ-провайдеры недоступны.
 * Один и тот же файл используется и на сервере (server/lib/story.js),
 * и в браузере (create.html) — если не отвечает сам сервер.
 *
 * Имя ребёнка склоняется только там, где оно стоит в именительном падеже
 * или в обращении, — остальное закрывают местоимения. Так текст остаётся
 * грамотным для любого имени.
 */
(function (root, factory) {
  var api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  else root.SkazkaTemplate = api;
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  function clean(value, max) {
    return String(value == null ? '' : value)
      .replace(/<[^>]*>/g, ' ')
      .replace(/\s+/g, ' ')
      .trim()
      .slice(0, max || 400);
  }

  function lowerFirst(s) { return s ? s.charAt(0).toLowerCase() + s.slice(1) : s; }
  function stripEnd(s) { return s.replace(/[\s.!?…,;:—-]+$/, ''); }

  function yearsWord(n) {
    var m10 = n % 10, m100 = n % 100;
    if (m10 === 1 && m100 !== 11) return 'год';
    if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return 'года';
    return 'лет';
  }

  // Библиотека фоновых сцен (файлы: assets/scenes/<тег>.jpg)
  var SCENES = {
    map_table: 'чердак со столом и старой картой',
    forest_path: 'лесная тропа',
    night_camp: 'ночной лагерь у костра',
    treasure_room: 'уютная комната с находками и сокровищами',
    cave_entrance: 'вход в пещеру',
    mountain_bridge: 'подвесной мост в горах',
    ship_deck: 'палуба корабля',
    castle_gate: 'старинный замок'
  };

  // Сцены по страницам для шаблонных историй; hero — страница с ребёнком (4-я по счёту с нуля)
  var TEMPLATE_SCENES = {
    adventure: ['map_table', 'forest_path', 'mountain_bridge', 'cave_entrance', 'cave_entrance', 'treasure_room'],
    fairytale: ['treasure_room', 'night_camp', 'forest_path', 'castle_gate', 'castle_gate', 'castle_gate'],
    holiday: ['treasure_room', 'forest_path', 'forest_path', 'night_camp', 'night_camp', 'treasure_room']
  };

  function themeKind(theme) {
    var t = String(theme || '');
    if (/сказ|fairy/i.test(t)) return 'fairytale';
    if (/праздн|повод|holiday/i.test(t)) return 'holiday';
    return 'adventure';
  }

  function normalize(input) {
    input = input || {};
    var girl = !/^(мал|boy|male|m$)/i.test(clean(input.gender, 30));
    var age = parseInt(input.age, 10);
    return {
      name: clean(input.name, 40) || 'Малыш',
      girl: girl,
      age: age >= 1 && age <= 17 ? age : null,
      eyes: stripEnd(clean(input.eyes, 40).replace(/\s*\(.*\)\s*/, '')),
      occasion: stripEnd(clean(input.occasion, 120)),
      habits: stripEnd(clean(input.habits, 400)),
      friends: stripEnd(clean(input.friends, 300)),
      cast: stripEnd(clean(input.cast, 300)),
      interests: stripEnd(clean(input.interests, 300)),
      special: stripEnd(clean(input.special, 400)),
      kind: themeKind(input.theme)
    };
  }

  function buildTemplateStory(input) {
    var c = normalize(input);
    var n = c.name;
    // g('он', 'она') — выбор формы по полу
    function g(boy, girl) { return c.girl ? girl : boy; }
    var v = g; // окончания глаголов: v('', 'а'), v('ся', 'ась')

    var ageLine = c.age ? g('Ему', 'Ей') + ' было ' + c.age + ' ' + yearsWord(c.age) + '. ' : '';
    var habitsLine = c.habits
      ? 'Дома о ' + g('нём', 'ней') + ' говорили так: «' + c.habits + '». Именно поэтому ' + g('он', 'она') + ' — ' + g('единственный', 'единственная') + ' в своём роде.'
      : 'С ' + g('ним', 'ней') + ' никогда не бывает скучно — и в этом весь секрет.';
    var friendsLine = c.friends
      ? 'Рядом были друзья: ' + c.friends + '.'
      : 'Рядом был верный друг, готовый пойти за ' + g('ним', 'ней') + ' хоть на край света.';
    var castLine = c.cast
      ? 'Вспомнились те, кто ждёт дома и верит в ' + g('него', 'неё') + ': ' + c.cast + '.'
      : 'Вспомнились самые близкие, которые ждут дома и верят в ' + g('него', 'неё') + '.';
    var castHoliday = c.cast ? 'Среди них были самые близкие: ' + c.cast + '.' : 'Среди них были все самые близкие люди.';
    // «Карие» -> «карих»: цвет ставим в родительный падеж, иначе опускаем
    var eyesGen = /(ые|ие)$/i.test(c.eyes) ? lowerFirst(c.eyes).replace(/(ые|ие)$/i, function (m) { return m.toLowerCase() === 'ые' ? 'ых' : 'их'; }) : '';
    var eyesLine = eyesGen
      ? 'В глазах ' + g('мальчика', 'девочки') + ' — ' + eyesGen + ', широко распахнутых — отражались тысячи огоньков.'
      : 'В глазах ' + g('мальчика', 'девочки') + ' отражались тысячи огоньков.';
    var who = g('мальчик', 'девочка');

    var title, pages;

    if (c.kind === 'fairytale') {
      title = n + ' и волшебное королевство';
      pages = [
        'Жил' + v('', 'а') + ' на свете ' + who + ' по имени ' + n + '. ' + ageLine + habitsLine,
        'Однажды вечером, когда за окном зажглись первые звёзды, на подоконник опустился маленький серебристый мотылёк. «' + n + '! — прошептал он. — В волшебном королевстве пропал самый добрый свет, и только ' + g('мальчик', 'девочка') + ' с большим сердцем сможет вернуть его!»',
        n + ' немного удивил' + v('ся', 'ась') + ', но храбро кивнул' + v('', 'а') + ' — и мотылёк повёл ' + g('его', 'её') + ' через шкаф, где вместо стенки вдруг зашумел цветущий сад. ' + friendsLine,
        'Королевство встретило гостей тишиной: фонари не горели, фонтаны молчали. У тёмной башни ' + n + ' остановил' + v('ся', 'ась') + '. Лестница уходила во мрак, и стало немного тревожно. Но ' + n + ' вспомнил' + v('', 'а') + ': самое важное — не то, что страшно, а то, что ты всё равно идёшь. ' + castLine,
        '— Я справлюсь! — сказал' + v('', 'а') + ' ' + n + ' и шагнул' + v('', 'а') + ' на первую ступеньку. С каждым шагом лестница светилась всё ярче. На самом верху в хрустальном шаре билось маленькое золотое сердце королевства. ' + eyesLine,
        n + ' осторожно взял' + v('', 'а') + ' сердце в ладони — и по всему королевству вспыхнули фонари, зашумели фонтаны, а из окон высыпали жители. «Ура!» — кричали они, и громче всех — мотылёк. Так ' + n + ' стал' + v('', 'а') + ' почётным гостем королевства, а дома ждали тёплый чай и любимые люди. Конец.'
      ];
    } else if (c.kind === 'holiday') {
      title = n + ' и самый волшебный праздник';
      var day = c.occasion ? 'Наступил особенный день: ' + lowerFirst(c.occasion) + '.' : 'Наступил особенный день.';
      pages = [
        'Жил' + v('', 'а') + ' на свете ' + who + ' по имени ' + n + '. ' + ageLine + habitsLine,
        day + ' Утром ' + n + ' проснул' + v('ся', 'ась') + ' раньше всех и увидел' + v('', 'а') + ' на подушке маленький золотой конверт. Внутри лежала записка: «Сегодня в твой день случится настоящее волшебство. Следуй за огоньками!»',
        'Огоньки-светлячки вели ' + g('его', 'её') + ' по комнатам, во двор, за калитку, а потом — по тропинке к старой поляне. ' + friendsLine + ' Все шептались и загадочно улыбались, и ' + n + ' никак не мог' + v('', 'ла') + ' догадаться, что же будет дальше.',
        'На поляне вдруг погасли все огоньки. Стало тихо и немного тревожно. ' + n + ' замер' + v('', 'ла') + ', но вспомнил' + v('', 'а') + ', что смелость — это когда сердце стучит, а ты всё равно идёшь вперёд. И ' + g('он', 'она') + ' громко сказал' + v('', 'а') + ': «Я здесь!»',
        'И тут — вспышка! Загорелись сотни гирлянд, зазвенели колокольчики, и из-за деревьев вышли все, кого ' + n + ' любит. ' + castHoliday + ' ' + eyesLine,
        'Они пели, смеялись и танцевали, а потом загадали общее желание — самое светлое на свете. ' + n + ' понял' + v('', 'а') + ': лучший подарок — не то, что лежит в коробке, а те, кто рядом. С этим праздником ' + n + ' вернул' + v('ся', 'ась') + ' домой ' + g('счастливым', 'счастливой') + '. Конец.'
      ];
    } else {
      title = n + ' и тайна волшебной карты';
      pages = [
        'Жил' + v('', 'а') + ' на свете ' + who + ' по имени ' + n + '. ' + ageLine + habitsLine,
        'Однажды утром ' + n + ' ' + g('нашёл', 'нашла') + ' под подушкой старую карту. Красная нитка вела к Сияющей поляне, а внизу мелким почерком было написано: «Клад достанется тому, кто добр и смел». — Это же для меня! — воскликнул' + v('', 'а') + ' ' + n + '.',
        'Но идти ' + g('одному', 'одной') + ' не пришлось. ' + friendsLine + ' Вместе они перешли ручей по скользким камням, прошли через шепчущий лес и наконец увидели вход в тёмную пещеру.',
        'Из пещеры тянуло прохладой, а в глубине эхом отдавались капли. ' + n + ' остановил' + v('ся', 'ась') + ' и глубоко вздохнул' + v('', 'а') + '. Стало немного не по себе — но именно в такие минуты и проверяется настоящая смелость. ' + castLine,
        '— Я справлюсь! — сказал' + v('', 'а') + ' ' + n + ' и сделал' + v('', 'а') + ' первый шаг. Эхо повторило: «справлюсь-справлюсь». Фонарик засиял ярче, стены заискрились, и открылся зал, полный светящихся кристаллов. ' + eyesLine,
        'В самой середине зала стояла шкатулка. Внутри — записка: «Настоящий клад — это ты сам и те, кто идёт рядом». ' + n + ' улыбнул' + v('ся', 'ась') + ': ' + g('он', 'она') + ' и так это знал' + v('', 'а') + '. Домой ' + n + ' возвращал' + v('ся', 'ась') + ' затемно, ' + g('усталым', 'усталой') + ' и невероятно ' + g('счастливым', 'счастливой') + '. Конец.'
      ];
    }

    var scenes = TEMPLATE_SCENES[c.kind];
    return {
      title: title,
      pages: pages.map(function (text, i) { return { text: text, scene: scenes[i], hero: i === 4 }; })
    };
  }

  return { buildTemplateStory: buildTemplateStory, normalizeInput: normalize, cleanText: clean, SCENES: SCENES };
});
